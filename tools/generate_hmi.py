"""Generate the HMI v2 layout header and field contract from the DWIN panel package.

Reads vp_map.csv, font_widths.csv, events.csv and package/manifest.json from the panel
package folder (read only) and writes:

  firmware/TunnelESP32/src/hmi/HmiLayout.h   VP addresses, sizes, X registers, text boxes,
                                             faces, glyph widths, page ids, field ids, events
  contracts/hmi_fields.json                  connection text fields (hardware UART diagnostic)

  python tools/generate_hmi.py <package_dir> [--check]

No external packages. Nothing in the package folder is modified.
"""

import argparse
import csv
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
HEADER = "firmware/TunnelESP32/src/hmi/HmiLayout.h"
CONTRACT = "contracts/hmi_fields.json"
EVENT_VP = 0x1090
# Largest text write the firmware makes (bytes, FF FF included). Header and CRC added,
# the frame stays under 120 bytes: the largest single item of the 256-byte UART queue.
MAX_TEXT_BYTES = 110


def rows(path):
    with open(path, encoding="utf8", newline="") as handle:
        return list(csv.DictReader(handle))


def slug(text):
    return re.sub(r"[^A-Za-z0-9]+", "_", text).strip("_").upper()


def products(package):
    vps = rows(package / "vp_map.csv")
    fonts = rows(package / "font_widths.csv")
    events = rows(package / "events.csv")
    manifest = json.loads((package / "package/manifest.json").read_text(encoding="utf8"))
    assert int(manifest["event_vp"]) == EVENT_VP or int(str(manifest["event_vp"]), 16) == EVENT_VP
    assert all(int(e["vp_hex"], 16) == EVENT_VP for e in events)
    names = [r["name"] for r in vps]
    assert len(set(names)) == len(names) and all(re.fullmatch(r"[a-z0-9_]+", n) for n in names)

    faces = [f["face"] for f in fonts]
    out = "// Generated by tools/generate_hmi.py from the DWIN panel package; do not edit.\n"
    out += "// Panel: " + manifest["panel"] + "\n#pragma once\n#include <stdint.h>\n\n"
    out += "#define HMIL_EVENT_VP 0x%04XU\n" % EVENT_VP
    out += "/* Text fields larger than this get their first bytes only (always with FF FF). */\n"
    out += "#define HMIL_MAX_TEXT_BYTES %dU\n\n" % MAX_TEXT_BYTES
    out += "/* Every panel variable (vp_map.csv). */\n"
    for r in vps:
        out += "#define HMIL_VP_%s 0x%04XU\n" % (r["name"].upper(), int(r["vp_hex"], 16))

    # Variables the UI module publishes: displayed texts and the words new in v2. Existing
    # words (quantity, lamps, mode) stay with the machine code; scratch words are never written.
    items = [
        r
        for r in vps
        if (r["type"] == "text" and not r["meaning_or_initial"].startswith("not displayed"))
        or (r["type"] == "word" and r["firmware_1_12_3"] == "NEW")
    ]
    index = {r["name"]: i for i, r in enumerate(items)}
    for name, i in index.items():  # numbered families must be consecutive (indexed in code)
        m = re.fullmatch(r"(.*?)(\d+)", name)
        if m and int(m.group(2)) > 1:
            assert index.get(m.group(1) + str(int(m.group(2)) - 1)) == i - 1, name
    out += "\n/* Glyph width tables (font_widths.csv). 0 = glyph missing, drawn as a space. */\n"
    out += "enum HmilFace { " + ", ".join("HMIL_FACE_" + f.upper() for f in faces)
    out += ", HMIL_FACE_COUNT, HMIL_FACE_NONE = 255 };\n"
    out += "struct HmilFont {\n    uint8_t gap, space;\n    uint8_t width[94];\n};\n"
    out += "static const struct HmilFont HMIL_FONTS[HMIL_FACE_COUNT] = {\n"
    for f in fonts:
        widths = []
        for code in range(0x21, 0x7F):
            cell = f.get("%02X" % code, "")
            assert cell == "" or 0 < int(cell) < 256, (f["face"], code)
            widths.append(int(cell) if cell else 0)
        out += "    {%d, %d, {%s}},\n" % (
            int(f["gap_after_glyph"]),
            int(f["space_width"]),
            ", ".join(map(str, widths)),
        )
    out += (
        "};\n\n/* Variables published by the UI module, in vp_map.csv order. */\nenum HmilItem {\n"
    )
    for r in items:
        out += "    HMIL_ITEM_%s,\n" % r["name"]
    out += (
        "    HMIL_ITEM_COUNT\n};\nenum { HMIL_ALIGN_LEFT, HMIL_ALIGN_RIGHT, HMIL_ALIGN_CENTER };\n"
    )
    out += "struct HmilVar {\n    uint16_t vp, bytes, x_register, box_left, box_right;\n"
    out += "    uint8_t face, align, text;\n};\n"
    out += "static const struct HmilVar HMIL_ITEMS[HMIL_ITEM_COUNT] = {\n"
    for r in items:
        text = r["type"] == "text"
        size = int(r["bytes"])
        assert size % 2 == 0 and (text or size == 2), r["name"]
        align = r["align"] or "left"
        aligned = align in ("right", "center")
        assert align in ("left", "right", "center") and aligned == bool(r["x_register_hex"])
        assert not text or r["face"] in faces, r["name"]
        out += "    {0x%04X, %d, 0x%04X, %d, %d, %s, HMIL_ALIGN_%s, %d}, /* %s */\n" % (
            int(r["vp_hex"], 16),
            size,
            int(r["x_register_hex"], 16) if aligned else 0,
            int(r["box_left"] or 0),
            int(r["box_right"] or 0),
            "HMIL_FACE_" + r["face"].upper() if text else "HMIL_FACE_NONE",
            align.upper(),
            text,
            r["name"],
        )
    out += "};\n\n/* Page ids (package/manifest.json). */\nenum HmilPage {\n"
    pages = sorted((int(k), v["name"]) for k, v in manifest["pages"].items())
    for number, name in pages:
        out += "    HMIL_PAGE_%s = %d,\n" % (name, number)
    out += "    HMIL_PAGE_LAST = %d\n};\n" % pages[-1][0]

    # Field ids come from the event codes: 02ff = field tapped, 2ffo = segmented option.
    fields, options, fixed = {}, {}, []
    for e in events:
        value, meaning = int(e["value_hex"], 16), e["meaning"]
        if value >> 8 == 2:
            fields[value & 255] = meaning.split(": ")[1]
        elif value & 0xF000 == 0x2000:
            number, name = (value >> 4) & 255, meaning.split(" = ")[0]
            assert fields.setdefault(number, name) == name
            options[number] = max(options.get(number, 0), value & 15)
        elif value >> 8 in (5, 7):
            fixed.append((value, slug(meaning)))
    count = max(fields)
    assert sorted(fields) == list(range(1, count + 1)), "field ids must be contiguous"
    out += "\n/* Field ids and fixed event codes (events.csv). */\nenum HmilField {\n"
    for number in range(1, count + 1):
        out += "    HMIL_FIELD_%s = %d,\n" % (fields[number], number)
    out += "    HMIL_FIELD_COUNT = %d\n};\n" % count
    out += "/* Per field id: text item, sel_ word item (255 = none), segmented option count. */\n"
    out += "struct HmilFieldVar {\n    uint8_t text_item, sel_item, options;\n};\n"
    out += "static const struct HmilFieldVar HMIL_FIELDS[HMIL_FIELD_COUNT + 1] = {\n"
    out += "    {255, 255, 0},\n"
    for number in range(1, count + 1):
        name = fields[number]
        text, sel = index.get(name, 255), index.get("sel_" + name, 255)
        assert text < 255 or sel < 255, name
        assert (sel < 255) == (number in options), name
        out += "    {%d, %d, %d}, /* %s */\n" % (text, sel, options.get(number, 0), name)
    out += "};\nenum HmilEvent {\n"
    for value, name in fixed:
        out += "    HMIL_EV_%s = 0x%04X,\n" % (name, value)
    out += "    HMIL_EV_NONE = 0\n};\n"
    yield HEADER, out

    # Connection texts observed by tests/verify_device_uart.py:
    # name -> [vp, bytes the firmware writes, initial].
    network = {}
    for number in range(1, count + 1):
        r = next((v for v in vps if v["name"] == fields[number]), None)
        if r and r["type"] == "text" and r["firmware_1_12_3"] == "yes":
            network[r["name"]] = [int(r["vp_hex"], 16), min(int(r["bytes"]), MAX_TEXT_BYTES), "--"]
    yield CONTRACT, json.dumps({"fields": network}, indent=2) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("package", type=Path, help="Tunnel_HMI_DWIN_Package_v2 folder")
    parser.add_argument("--check", action="store_true", help="Fail on stale generated files")
    args = parser.parse_args()
    bad = []
    for name, content in products(args.package):
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                bad.append(name)
        else:
            path.write_text(content, encoding="utf-8", newline="\n")
    if bad:
        raise SystemExit("Stale generated files: " + ", ".join(bad))
    print("PASS HMI layout is current" if args.check else "Generated HMI layout")


if __name__ == "__main__":
    main()
