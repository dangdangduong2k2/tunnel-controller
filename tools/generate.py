"""Generate wire catalogs, version constants and embedded web UI. No external packages."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def products():
    release = json.loads((ROOT / "contracts/release.json").read_text(encoding="utf-8"))
    ops = json.loads((ROOT / "contracts/operations.json").read_text(encoding="utf-8"))
    assert len({o["op"] for o in ops}) == len(ops)
    assert len({o["method"] for o in ops}) == len(ops)
    for op in ops:
        assert len(op["params"]) <= 6
        assert all(0 <= p[1] <= p[2] <= 65535 for p in op["params"])
    header = "// Generated by tools/generate.py; edit contracts/release.json.\n#pragma once\n"
    for name, value in {
        "TUNNEL_VERSION": release["version"],
        "TUNNEL_FIRMWARE_NAME": "Tunnel-3Protocol-" + release["version"],
        "TUNNEL_FIRMWARE_REGISTER": release["firmware_register"],
        "TUNNEL_REGISTER_MAP": release["register_map"],
        "TUNNEL_MQTT_API": release["mqtt_api"],
    }.items():
        header += f"#define {name} {json.dumps(value)}\n"
    yield "firmware/TunnelESP32/src/common/Version.h", header
    cat = """// Generated by tools/generate.py; edit contracts/operations.json.
#pragma once
#include <stdint.h>
namespace tunnelcontract {
struct Parameter { const char *name; uint16_t minimum, maximum; };
struct Operation { uint16_t op; const char *method; uint8_t count; Parameter params[6]; };
static constexpr Operation OPERATIONS[] = {
"""
    for o in ops:
        params = ",".join('{"%s",%d,%d}' % tuple(p) for p in o["params"])
        cat += '{%d,"%s",%d,{%s}},\n' % (o["op"], o["method"], len(o["params"]), params)
    cat += "};\n} // namespace tunnelcontract\n"
    yield "firmware/TunnelESP32/src/common/OperationCatalog.h", cat
    py = "# Generated by tools/generate.py; edit contracts/operations.json.\n"
    py += (
        "CATALOG = "
        + repr({o["method"]: {"op": o["op"], "params": o["params"]} for o in ops})
        + "\n"
    )
    py += 'OPERATIONS = {name: spec["op"] for name, spec in CATALOG.items()}\n'
    yield "api/tunnel_sdk/operations.py", py
    md = "# Danh sách lệnh chung\n\nSinh từ [operations.json](../contracts/operations.json). MQTT và Modbus gọi cùng backend.\n\n"
    md += "Tham số theo thứ tự ARG0..ARG5; các ô còn lại phải bằng 0. MQTT named API yêu cầu đủ các trường trong `params`, số nguyên (không dùng `true/false`). Mọi lệnh cần quyền điều khiển; các lệnh reader còn cần maintenance và reader rảnh. ACK nhận lệnh chưa đồng nghĩa chuyển động/reader đã hoàn tất.\n\n"
    md += "| OP | Method | Tham số bắt buộc, khoảng | Tác động |\n|---:|---|---|---|\n"
    for o in ops:
        params = "; ".join(f"`{p[0]}`: {p[1]}..{p[2]}" for p in o["params"]) or "`{}` / không có"
        md += f'| {o["op"]} | `{o["method"]}` | {params} | {o["effect"]} |\n'
    yield "docs/COMMANDS.md", md
    html = (ROOT / "web/index.html").read_text(encoding="utf-8")
    assert ')TUNNELWEB"' not in html
    chunks = [html[i : i + 4000] for i in range(0, len(html), 4000)]
    literals = "\n".join('R"TUNNELWEB(' + chunk + ')TUNNELWEB"' for chunk in chunks)
    yield (
        "firmware/TunnelESP32/src/web/ConfigPage.h",
        "// Generated from web/index.html by tools/generate.py.\n#pragma once\nstatic const char CONFIG_PAGE[] =\n"
        + literals
        + ";\n",
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="Fail on missing/stale generated files"
    )
    args = parser.parse_args()
    bad = []
    for name, content in products():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                bad.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    if bad:
        raise SystemExit("Stale generated files: " + ", ".join(bad))
    print("PASS generated contracts and web UI" if args.check else "Generated contracts and web UI")


if __name__ == "__main__":
    main()
