"""Embed only the verified Scan START/STOP migration. Never opens a serial port."""
import argparse
import hashlib
import json
from pathlib import Path
import zlib

ROOT = Path(__file__).resolve().parents[1]


def crc16(data):
    value = 0xffff
    for byte in data:
        value ^= byte
        for _ in range(8):
            value = (value >> 1) ^ (0xa001 if value & 1 else 0)
    return value


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('before', type=Path)
    p.add_argument('after', type=Path)
    p.add_argument('--check', action='store_true')
    a = p.parse_args()
    before = (a.before / 'font13.bin').read_bytes()
    after = (a.after / 'font13.bin').read_bytes()
    assert len(before) == len(after) == 262144
    diff = [(i, x, y) for i, (x, y) in enumerate(zip(before, after)) if x != y]
    assert diff == [(341, 1, 2), (373, 1, 3)], diff
    # Independently check the touch VP and value for each record, not just hashes.
    for off, value in ((320, 2), (352, 3)):
        assert after[off:off+2] == b'\0\1'
        assert after[off+14:off+19] == bytes.fromhex('fe05fe1020')
        assert int.from_bytes(after[off+20:off+22], 'big') == value
    manifest = json.loads((a.after / 'manifest.json').read_text(encoding='utf8'))
    fingerprints = []
    for slot in (14, 16, 17, 18, 19, 20, 21, 22, 24, 25, 26, 27):
        name = f'font{slot}.bin'
        data = (a.after / name).read_bytes()
        assert len(data) == 262144 and data == (a.before / name).read_bytes()
        assert hashlib.sha256(data).hexdigest() == manifest['files'][str(slot)]['sha256']
        fingerprints.append((slot, crc16(data)))
    data = after[:32768]
    text = '// Generated by tools/generate_dwin_patch.py; do not edit.\n'
    text += '#pragma once\n#include "DwinPatch.h"\nnamespace dwinpatchdata {\n'
    text += f'// Full font13 SHA256: {hashlib.sha256(after).hexdigest()}\n'
    text += 'static const uint8_t BLOCK[32768] = {\n'
    for i in range(0, len(data), 24):
        text += '    ' + ','.join(f'0x{x:02x}' for x in data[i:i+24]) + ',\n'
    text += '};\nstatic const dwinpatch::Fingerprint REST[] = {\n'
    text += ''.join(f'    {{{slot},0x{crc:04x}}},\n' for slot, crc in fingerprints)
    text += '};\nstatic const dwinpatch::Image IMAGE = {BLOCK,'
    text += f'0x{crc16(before):04x},0x{crc16(after):04x},REST,sizeof(REST)/sizeof(REST[0]),0x{zlib.crc32(after):08x}UL'
    text += '};\n} // namespace dwinpatchdata\n'
    target = ROOT / 'firmware/TunnelESP32/src/hmi/DwinScanPatchData.h'
    if a.check:
        assert target.read_text(encoding='utf8') == text, 'stale DWIN patch header'
    else:
        target.write_text(text, encoding='utf8')
    print('PASS DWIN migration: exact two-byte change, 12 unchanged slots, 32 KiB embedded block')


if __name__ == '__main__':
    main()
